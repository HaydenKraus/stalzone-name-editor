def categorize(key: str, pack: str = "") -> str:
    """Вернуть категорию по ключу локализации."""
    if key.startswith("item."):
        parts = key.split(".")
        token = parts[1] if len(parts) > 1 else ""
        if token in ITEM_CATEGORY:
            return ITEM_CATEGORY[token]
        if token.isdigit():
            return "Квестовые"
        if token.startswith(EVENT_PREFIXES):
            return "Событийные"
        return "Разное"

    for prefix, category in PREFIX_RULES:
        if key.startswith(prefix):
            return category

    if pack == "gloomycore":
        return "Интерфейс"
    return "Прочее"
